#!/usr/bin/env python3
"""Requirements traceability matrix (STANDARDS section 22).

Reads the user requirements (URS), the product requirements (PRS), the calculation notes, the
build plan, the BOM and the drawing sheets, and writes docs/03b-traceability.md (PRJ-RTM-001):
user requirement -> product requirement -> evidence -> verification, with the gaps flagged.

Usage (from the repo root):
    python .kit/trace.py            # write or refresh the matrix
    python .kit/trace.py --check    # exit 1 if the matrix is missing or out of date, or a High UR has no PR
"""
import datetime, hashlib, re, sys
from pathlib import Path
import yaml

ROOT = Path.cwd()
OUT = ROOT / "docs/03b-traceability.md"
URS = ROOT / "docs/03a-user-requirements.md"
PRS = ROOT / "docs/03-requirements.md"
FM_RE = re.compile(r"^---\n(.*?)\n---\n", re.S)


def front(path):
    m = FM_RE.match(path.read_text(encoding="utf-8"))
    return (yaml.safe_load(m.group(1)) or {}) if m else {}


def tables(text):
    """Yield (header, rows) for every pipe table, cells stripped of markdown emphasis."""
    lines = text.splitlines()
    i = 0
    while i < len(lines) - 1:
        if lines[i].lstrip().startswith("|") and re.match(r"^\s*\|\s*:?-{3,}", lines[i + 1]):
            cells = lambda l: [c.strip().strip("*").strip() for c in l.strip().strip("|").split("|")]
            head, rows, j = [h.lower() for h in cells(lines[i])], [], i + 2
            while j < len(lines) and lines[j].lstrip().startswith("|"):
                rows.append(dict(zip(head, cells(lines[j])))); j += 1
            yield head, rows
            i = j
        else:
            i += 1


def rows_with(path, prefix):
    if not path.exists():
        return []
    out = []
    for head, rows in tables(path.read_text(encoding="utf-8")):
        if "id" in head:
            out += [r for r in rows if r.get("id", "").startswith(prefix)]
    return out


def evidence_sources():
    src = []
    for p in sorted((ROOT / "docs/04-calcs").glob("*.md")):
        src.append((p, front(p).get("doc_id", p.name)))
    for name in ("docs/05-build-plan.md", "docs/01b-stem-check.md", "docs/02a-concept-options.md"):
        p = ROOT / name
        if p.exists():
            src.append((p, front(p).get("doc_id", p.name)))
    for p in sorted((ROOT / "bom").glob("*.csv")):
        src.append((p, "BOM"))
    return src


def find_evidence(pr, sources):
    keys = [pr["id"]] + [k.strip() for k in re.split(r"[,; ]+", pr.get("was", "")) if re.fullmatch(r"R\d+[a-z]?", k.strip())]
    hits = []
    for p, label in sources:
        text = p.read_text(encoding="utf-8", errors="ignore")
        if any(re.search(rf"(?<![\w-]){re.escape(k)}(?![\w])", text) for k in keys):
            hits.append(label)
    return hits


def build():
    pm = yaml.safe_load((ROOT / "project.yaml").read_text()) or {}
    urs, prs = rows_with(URS, "UR-"), rows_with(PRS, "PR-")
    sources = evidence_sources()
    digest = hashlib.sha256(b"".join(p.read_bytes() for p in [URS, PRS] + [s for s, _ in sources] if p.exists())).hexdigest()[:16]
    by_ur = {u["id"]: [] for u in urs}
    gaps, lines = [], []
    for pr in prs:
        traced = re.findall(r"UR-\d{3}", pr.get("traces to", ""))
        if not traced:
            gaps.append(f"{pr['id']} traces to no user requirement (candidate to drop)")
        for u in traced:
            if u in by_ur:
                by_ur[u].append(pr["id"])
            else:
                gaps.append(f"{pr['id']} traces to {u}, which is not in URS")
        ev = find_evidence(pr, sources)
        if not ev and not pr.get("status", "").lower().startswith("withdrawn"):
            gaps.append(f"{pr['id']} has no evidence in the calculations, build plan or BOM")
        if not pr.get("verification"):
            gaps.append(f"{pr['id']} has no verification method")
        lines.append(f"| {', '.join(traced) or 'none'} | {pr['id']} | {pr.get('title', '')} | {', '.join(ev) or 'none'} | {pr.get('verification', '')} | {pr.get('status', '')} |")
    for u in urs:
        if not by_ur[u["id"]]:
            sev = "High" if u.get("priority", "").lower().startswith("h") else u.get("priority", "")
            gaps.append(f"{u['id']} ({sev}) has no product requirement")
    code = str(pm.get("doc_prefix") or "")
    if not code:
        prb = ROOT / "docs/01-problem.md"
        code = str(front(prb).get("doc_id", "PRJ-PRB-001")).split("-")[0] if prb.exists() else "PRJ"
    old = front(OUT) if OUT.exists() else {}
    if old.get("source_hash") == digest:
        return old, digest, gaps, None
    today = datetime.date.today().isoformat()
    revs = old.get("revisions") or []
    ver = "0.1" if not revs else f"0.{int(str(revs[-1]['version']).split('.')[1]) + 1}"
    revs.append({"version": ver, "date": today, "author": "Amish Chadha", "change": "Generated by .kit/trace.py"})
    meta = {"doc_id": f"{code}-RTM-001", "title": f"{pm.get('name', 'Project')} traceability matrix", "project": pm.get("name", ""),
            "doc_type": "Traceability matrix", "version": ver, "status": "Draft", "date": today, "author": "Amish Chadha",
            "license": (pm.get("licenses") or {}).get("hardware", "CERN-OHL-S-2.0"), "source_hash": digest, "revisions": revs}
    body = [f"# {meta['title']}", "",
            f"Generated by `python .kit/trace.py` from the user requirements, product requirements, calculations, build plan and BOM. Do not edit by hand. {len(urs)} user requirements, {len(prs)} product requirements, {len(gaps)} gaps.", "",
            "Table 1. User requirement to product requirement to evidence to verification.", "",
            "| User requirement | Product requirement | Title | Evidence | Verification | Status |", "| --- | --- | --- | --- | --- | --- |", *lines, "",
            "## Gaps", ""] + ([f"- {g}" for g in gaps] or ["None."])
    text = "---\n" + yaml.safe_dump(meta, sort_keys=False, allow_unicode=True) + "---\n\n" + "\n".join(body) + "\n"
    return meta, digest, gaps, text


def main():
    if not (URS.exists() and PRS.exists()):
        print("FAIL user or product requirements missing (docs/03a-user-requirements.md, docs/03-requirements.md)")
        sys.exit(1)
    meta, digest, gaps, text = build()
    high = [g for g in gaps if "(High) has no product requirement" in g]
    if "--check" in sys.argv:
        bad = []
        if not OUT.exists():
            bad.append("traceability matrix missing; run python .kit/trace.py")
        elif text is not None:
            bad.append("traceability matrix is out of date; run python .kit/trace.py")
        bad += high
        for b in bad:
            print(f"FAIL {b}")
        for g in gaps:
            if g not in high:
                print(f"warn {g}")
        sys.exit(1 if bad else 0)
    if text is None:
        print(f"ok   {OUT.relative_to(ROOT)} up to date ({len(gaps)} gaps)")
    else:
        OUT.write_text(text, encoding="utf-8")
        print(f"wrote {OUT.relative_to(ROOT)} v{meta['version']} ({len(gaps)} gaps)")
    for g in gaps:
        print(f"gap  {g}")


if __name__ == "__main__":
    main()
